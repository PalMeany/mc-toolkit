package io.github.palmeany.mctoolkit.bridge;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.lang.reflect.Method;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

/**
 * Maps Mojang (official) names to the names the running server actually uses.
 *
 * <ul>
 *   <li>{@code mojang}: NeoForge 1.20.5+, Forge 1.20.6+ and every loader on the unobfuscated
 *       26.x line. Names are used as written; no table.</li>
 *   <li>{@code intermediary}: Fabric/Quilt 1.20.1 .. 1.21.11 ({@code class_1234}, {@code method_1234},
 *       {@code field_1234}).</li>
 *   <li>{@code srg}: Forge and NeoForge 1.20.1 .. 1.20.4 (Mojang class names, {@code m_1234_} /
 *       {@code f_1234_} members).</li>
 * </ul>
 *
 * The tables are generated by {@code tools/gen_names.py} from the official mapping files. The
 * namespace is detected by probing {@code MinecraftServer#getPlayerList()} under each name.
 */
final class Names {

    enum Namespace {
        MOJANG("mojang"), INTERMEDIARY("intermediary"), SRG("srg");

        final String id;

        Namespace(String id) {
            this.id = id;
        }
    }

    static final String SERVER = "net.minecraft.server.MinecraftServer";
    private static final String PROBE = SERVER + "#getPlayerList()";

    final Namespace namespace;
    final ClassLoader loader;
    private final Map<String, List<String>> classes;
    private final Map<String, List<String>> members;

    private Names(Namespace namespace, ClassLoader loader, Table table) {
        this.namespace = namespace;
        this.loader = loader;
        this.classes = table.classes;
        this.members = table.members;
    }

    static Names detect(Class<?> serverClass) {
        ClassLoader loader = serverClass.getClassLoader() != null ? serverClass.getClassLoader() : Names.class.getClassLoader();
        if (hasNoArgMethod(serverClass, List.of("getPlayerList"))) {
            return new Names(Namespace.MOJANG, loader, new Table());
        }
        for (Namespace ns : new Namespace[] {Namespace.INTERMEDIARY, Namespace.SRG}) {
            Table table = Table.load(ns.id);
            if (hasNoArgMethod(serverClass, table.members.getOrDefault(PROBE, List.of()))) {
                return new Names(ns, loader, table);
            }
        }
        Log.warn("Unrecognised runtime names on " + serverClass.getName() + "; assuming Mojang names (most data will be missing)");
        return new Names(Namespace.MOJANG, loader, new Table());
    }

    /** Runtime class for a Mojang class name (primitives and JDK/library classes pass through), or null. */
    Class<?> type(String mojang) {
        switch (mojang) {
            case "int": return int.class;
            case "long": return long.class;
            case "double": return double.class;
            case "float": return float.class;
            case "boolean": return boolean.class;
            case "short": return short.class;
            case "byte": return byte.class;
            case "char": return char.class;
            default: break;
        }
        for (String candidate : classes.getOrDefault(mojang, List.of(mojang))) {
            try {
                return Class.forName(candidate, false, loader);
            } catch (ClassNotFoundException | LinkageError ignored) {
                // try the next candidate
            }
        }
        return null;
    }

    /** Runtime names to try for a method, in order; empty when this runtime has none. */
    List<String> methodNames(String owner, String name, List<String> params) {
        if (namespace == Namespace.MOJANG || name.equals("<init>")) {
            return List.of(name);
        }
        return members.getOrDefault(owner + "#" + name + "(" + String.join(",", params) + ")", List.of());
    }

    /** Runtime names to try for a field, in order; empty when this runtime has none. */
    List<String> fieldNames(String owner, String name) {
        if (namespace == Namespace.MOJANG) {
            return List.of(name);
        }
        return members.getOrDefault(owner + "#" + name, List.of());
    }

    private static boolean hasNoArgMethod(Class<?> type, List<String> names) {
        for (Class<?> c = type; c != null; c = c.getSuperclass()) {
            try {
                for (Method m : c.getDeclaredMethods()) {
                    if (m.getParameterCount() == 0 && names.contains(m.getName())) {
                        return true;
                    }
                }
            } catch (Throwable ignored) {
                // a class whose members cannot be listed: keep walking up
            }
        }
        return false;
    }

    /** One namespace's rows from {@code names/<ns>.tsv} plus the optional dev-only {@code <ns>-selftest.tsv}. */
    private static final class Table {
        final Map<String, List<String>> classes = new HashMap<>();
        final Map<String, List<String>> members = new HashMap<>();

        static Table load(String namespace) {
            Table table = new Table();
            table.read("names/" + namespace + ".tsv", true);
            table.read("names/" + namespace + "-selftest.tsv", false);
            return table;
        }

        private void read(String resource, boolean required) {
            try (InputStream in = Names.class.getResourceAsStream(resource)) {
                if (in == null) {
                    if (required) {
                        Log.warn("Name table " + resource + " is missing from the jar");
                    }
                    return;
                }
                BufferedReader reader = new BufferedReader(new InputStreamReader(in, StandardCharsets.UTF_8));
                for (String line; (line = reader.readLine()) != null; ) {
                    if (line.isEmpty() || line.startsWith("#")) {
                        continue;
                    }
                    String[] cols = line.split("\t");
                    switch (cols[0]) {
                        case "C" -> add(classes, cols[1], cols[2]);
                        case "F" -> add(members, cols[1] + "#" + cols[2], cols[3]);
                        case "M" -> add(members, cols[1] + "#" + cols[2] + cols[3], cols[4]);
                        default -> { }
                    }
                }
            } catch (IOException | RuntimeException e) {
                Log.warn("Could not read name table " + resource, e);
            }
        }

        private static void add(Map<String, List<String>> map, String key, String value) {
            List<String> list = map.computeIfAbsent(key, k -> new ArrayList<>(1));
            if (!list.contains(value)) {
                list.add(value);
            }
        }
    }
}
